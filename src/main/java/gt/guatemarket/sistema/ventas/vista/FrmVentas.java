    private void categoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_categoriaActionPerformed
        String nombreCategoria = (String) categoria.getSelectedItem();

        if (nombreCategoria == null) {
            return;
        }

        CategoriaDAO categoriaDAO = new CategoriaDAOImpl();

        List<Categoria> categorias = categoriaDAO.listar();

        String idCategoria = null;

        for (Categoria cat : categorias) {
            if (cat.getNombreCategoria().equals(nombreCategoria)) {
                idCategoria = cat.getIdCategoria();
                break;
            }
        }

        if (idCategoria == null) {
            return;
        }

        ProductoDAO dao = new ProductoDAOImpl();

        List<Producto> productos = dao.listarPorCategoria(idCategoria);

        DefaultTableModel modelo = (DefaultTableModel) catalogo.getModel();

        modelo.setRowCount(0);

        for (Producto producto : productos) {

            modelo.addRow(new Object[]{
                producto.getNombreProducto(),
                producto.getStock(),
                producto.getPrecio(),
                producto.getIdProducto()
            });
        }
    }//GEN-LAST:event_categoriaActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int fila = catalogo.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un producto de la tabla."
            );
            return;
        }

        String idProducto = catalogo.getValueAt(fila, 3).toString();
        String nombre = catalogo.getValueAt(fila, 0).toString();
        int stock = Integer.parseInt(
                catalogo.getValueAt(fila, 1).toString()
        );
        double precio = Double.parseDouble(
                catalogo.getValueAt(fila, 2).toString()
        );

        String cantidadTexto = JOptionPane.showInputDialog(
                this,
                "Ingrese la cantidad de " + nombre + ":"
        );

        if (cantidadTexto == null) {
            return;
        }

        try {

            int cantidad = Integer.parseInt(cantidadTexto);

            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(
                        this,
                        "La cantidad debe ser mayor a 0."
                );
                return;
            }

            if (cantidad > stock) {
                JOptionPane.showMessageDialog(
                        this,
                        "No hay suficiente stock.\nStock disponible: " + stock
                );
                return;
            }

            double total = cantidad * precio;

            DefaultTableModel modeloVenta
                    = (DefaultTableModel) productosVenta.getModel();

            modeloVenta.addRow(new Object[]{
                idProducto,
                cantidad,
                nombre,
                precio,
                total
            });

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese una cantidad válida."
            );
        }
    }//GEN-LAST:event_jButton1ActionPerformed

