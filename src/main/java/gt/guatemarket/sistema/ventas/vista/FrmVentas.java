    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (nombreCliente.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente.");
            return;
        }
        if (productosVenta.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Debe agregar al menos un producto.");
            return;
        }
        Venta venta = new Venta();
        venta.setNombre(nombreCliente.getText().trim());
        venta.setDpi(dpiCliente.getText().trim());
        venta.setNit(nitCliente.getText().trim());
        venta.setTelefono(telefonoCliente.getText().trim());
        venta.setCorreo(correoCliente.getText().trim());
        venta.setDireccion(direccionCliente.getText().trim());
        venta.setFechaVenta(java.time.LocalDate.now().toString());
        VentaDAO ventaDAO = new VentaDAOImpl();
        String idVenta = ventaDAO.guardar(venta);
        if (idVenta == null) {
            JOptionPane.showMessageDialog(this, "No se pudo guardar la venta.");
            return;
        }
        DetalleVentaDAO detalleDAO = new DetalleVentaDAOImpl();
        for (int i = 0; i < productosVenta.getRowCount(); i++) {
            DetalleVenta detalle = new DetalleVenta();
            detalle.setIdVenta(idVenta);
            detalle.setIdProducto(productosVenta.getValueAt(i, 0).toString());
            detalle.setCantidadProducto(Integer.parseInt(productosVenta.getValueAt(i, 1).toString()));
            detalle.setNombreProducto(productosVenta.getValueAt(i, 2).toString());
            detalle.setPrecioUnitario(Double.parseDouble(productosVenta.getValueAt(i, 3).toString()));
            detalle.setTotal(Double.parseDouble(productosVenta.getValueAt(i, 4).toString()));
            boolean guardado = detalleDAO.guardar(detalle);
            if (!guardado) {
                JOptionPane.showMessageDialog(this, "No se pudo guardar el detalle del producto:\n" + detalle.getNombreProducto());
                return;
            }
        }
        JOptionPane.showMessageDialog(this, "Venta guardada correctamente.");
    }//GEN-LAST:event_jButton2ActionPerformed


