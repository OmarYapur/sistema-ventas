    private void buscarClientesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarClientesActionPerformed
        String nombre = nombreCliente.getText().trim();

        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el nombre del cliente.");
            return;
        }

        ClienteDAO dao = new ClienteDAOImpl();

        Cliente cliente = dao.buscarPorNombre(nombre);

        if (cliente == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "No se encontró el cliente.",
                    "Cliente no encontrado",
                    JOptionPane.WARNING_MESSAGE);

            return;
        }

        dpiCliente.setText(cliente.getDpi());
        nitCliente.setText(cliente.getNit());
        telefonoCliente.setText(cliente.getTelefono());
        correoCliente.setText(cliente.getCorreo());
        direccionCliente.setText(cliente.getDireccion());
    }//GEN-LAST:event_buscarClientesActionPerformed

